from pathlib import Path
import json
from playwright.sync_api import sync_playwright, expect
import sys

BASE_URL = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:5173'

out = Path(__file__).parents[1] / 'test-results'
out.mkdir(exist_ok=True)
results = []
errors = []

def passed(name):
    results.append({'scenario':name, 'passed':True})
    print('PASS: ' + name, flush=True)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={'width':1440,'height':1000})
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(BASE_URL, wait_until='networkidle')
    expect(page.locator('.product-card')).to_have_count(12)
    page.screenshot(path=str(out/'desktop-home.png'))
    passed('Desktop renders 12 products with no runtime error')
    search = page.get_by_role('searchbox', name='搜索商品')
    search.fill('杯子')
    expect(page.locator('.product-card')).to_have_count(1)
    expect(page.locator('.product-card')).to_contain_text('云朵')
    page.get_by_role('button',name='桌面好物',exact=True).click()
    expect(page.locator('.product-card')).to_have_count(0)
    expect(page.get_by_text('还没找到这件好物')).to_be_visible()
    page.get_by_role('button',name='查看全部好物',exact=True).click()
    expect(page.locator('.product-card')).to_have_count(12)
    passed('Search/category intersection, no-results recovery and reset')
    page.get_by_label('商品排序').select_option('price-asc')
    expect(page.locator('.product-card').first).to_contain_text('灵感笔记本')
    page.reload(wait_until='networkidle')
    expect(page.get_by_label('商品排序')).to_have_value('price-asc')
    expect(page.locator('.product-card').first).to_contain_text('灵感笔记本')
    passed('Numeric sorting and URL state survive refresh')
    page.get_by_role('button',name='清空条件').click()
    page.get_by_role('link',name='查看云朵 · 陶瓷马克杯详情',exact=True).click()
    detail = page.get_by_role('dialog')
    expect(detail).to_be_visible()
    expect(page).to_have_url(__import__('re').compile('product=cloud-mug'))
    detail.get_by_role('button',name='增加云朵 · 陶瓷马克杯数量').click()
    detail.get_by_role('button',name=__import__('re').compile('加入购物车')).click()
    expect(detail.get_by_text('购物车已有 2 件',exact=False)).to_be_visible()
    page.keyboard.press('Escape')
    expect(detail).not_to_be_visible()
    expect(page.get_by_role('link',name='查看云朵 · 陶瓷马克杯详情',exact=True)).to_be_focused()
    passed('Product details, selected quantity, Escape and focus return')
    page.get_by_role('button',name='将云朵 · 陶瓷马克杯加入购物车',exact=True).click()
    page.get_by_role('button',name='将暖光 · 桌面台灯加入购物车',exact=True).click()
    page.get_by_role('button',name='打开购物车，共4件商品').click()
    cart = page.get_by_role('dialog')
    expect(cart.locator('.cart-item')).to_have_count(2)
    expect(cart.get_by_test_id('cart-subtotal')).to_have_text('¥506.00')
    cart.get_by_role('button',name='增加云朵 · 陶瓷马克杯数量').click()
    expect(cart.get_by_test_id('cart-subtotal')).to_have_text('¥595.00')
    cart.get_by_role('button',name='减少云朵 · 陶瓷马克杯数量').click()
    expect(cart.get_by_test_id('cart-subtotal')).to_have_text('¥506.00')
    cart.screenshot(path=str(out/'desktop-cart.png'))
    passed('Repeated add merges lines, quantities and exact totals')
    cart.get_by_role('button',name='立即购买',exact=True).click()
    purchase=page.get_by_role('dialog',name='购买功能，还在慢慢准备中')
    expect(purchase).to_be_visible()
    expect(purchase.get_by_text('下单与支付功能暂未实现',exact=False)).to_be_visible()
    purchase.screenshot(path=str(out/'purchase-notice.png'))
    purchase.get_by_role('button',name='返回购物车',exact=True).click()
    expect(cart.get_by_test_id('cart-subtotal')).to_have_text('¥506.00')
    expect(cart.get_by_role('button',name='立即购买',exact=True)).to_be_focused()
    passed('Buy-now friendly notice preserves cart and restores focus')
    cart.get_by_role('button',name='删除暖光 · 桌面台灯').click()
    expect(cart.locator('.cart-item')).to_have_count(1)
    page.get_by_role('button',name='撤销',exact=True).click(timeout=4000)
    expect(cart.locator('.cart-item')).to_have_count(2)
    expect(cart.get_by_test_id('cart-subtotal')).to_have_text('¥506.00')
    passed('Remove item and undo deletion')
    page.keyboard.press('Escape')
    page.reload(wait_until='networkidle')
    page.get_by_role('button',name='打开购物车，共4件商品').click()
    expect(page.get_by_test_id('cart-subtotal')).to_have_text('¥506.00')
    passed('Cart persists through a page reload')
    page.keyboard.press('Escape')

    # Verify every supplied image after scrolling lazy-loaded content into view.
    for image in page.locator('.product-photo img').all():
        image.scroll_into_view_if_needed()
        expect(image).to_have_js_property('complete',True)
        assert image.evaluate('(i)=>i.naturalWidth > 0')
    passed('All local product images load')

    for width, height in [(320,740),(375,812),(390,844),(768,1024),(844,390),(1024,768),(1440,1000)]:
        page.set_viewport_size({'width':width,'height':height})
        page.evaluate('window.scrollTo(0,0)')
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), f'Horizontal overflow at {width}'
    passed('No horizontal overflow at 320, 375, 390, 768, 844, 1024, 1440 px')

    mobile = browser.new_context(viewport={'width':390,'height':844}, is_mobile=True, has_touch=True, device_scale_factor=1)
    phone = mobile.new_page()
    phone.on('pageerror', lambda error: errors.append(str(error)))
    phone.goto(BASE_URL,wait_until='networkidle')
    phone.screenshot(path=str(out/'mobile-home.png'))
    phone.get_by_role('button',name='打开筛选与排序').click()
    panel=phone.get_by_role('dialog')
    panel.get_by_role('button',name='心意礼物',exact=True).click()
    panel.get_by_role('button',name='价格从低到高',exact=True).click()
    panel.get_by_role('button',name=__import__('re').compile('查看 .* 件好物')).click()
    expect(phone.locator('.product-card').first).to_contain_text('灵感笔记本')
    passed('Mobile filter sheet combines gift budget and sorting')
    phone.get_by_role('link',name='查看日记 · 灵感笔记本详情',exact=True).click()
    panel=phone.get_by_role('dialog')
    panel.get_by_role('button',name=__import__('re').compile('加入购物车')).click()
    panel.screenshot(path=str(out/'mobile-detail.png'))
    panel.locator('.go-cart').click()
    panel=phone.get_by_role('dialog')
    expect(panel.get_by_test_id('cart-subtotal')).to_have_text('¥49.00')
    panel.get_by_role('button',name='增加日记 · 灵感笔记本数量').click()
    expect(panel.get_by_test_id('cart-subtotal')).to_have_text('¥98.00')
    panel.get_by_role('button',name='立即购买',exact=True).click()
    purchase=phone.get_by_role('dialog',name='购买功能，还在慢慢准备中')
    expect(purchase).to_be_visible()
    purchase.get_by_role('button',name='返回购物车',exact=True).click()
    expect(panel.get_by_test_id('cart-subtotal')).to_have_text('¥98.00')
    passed('Mobile buy-now notice returns to unchanged cart')
    panel.screenshot(path=str(out/'mobile-cart.png'))
    panel.get_by_role('button',name='删除日记 · 灵感笔记本').click()
    expect(panel.get_by_text('给喜欢的好物，留个位置')).to_be_visible()
    panel.get_by_role('button',name='去逛逛',exact=True).click()
    passed('Mobile detail-to-cart, quantity and empty-cart recovery')

    # Corrupt storage must not break initial rendering.
    phone.evaluate("localStorage.setItem('cozy-corner-cart-v1','{broken')")
    phone.reload(wait_until='networkidle')
    expect(phone.get_by_role('button',name='打开购物车，共0件商品')).to_be_visible()
    passed('Malformed saved cart recovers safely')
    phone.emulate_media(reduced_motion='reduce')
    assert phone.evaluate("matchMedia('(prefers-reduced-motion: reduce)').matches")
    phone.get_by_role('button',name='将日记 · 灵感笔记本加入购物车').click()
    passed('Reduced-motion mode retains functional interactions')
    assert not errors, errors
    passed('No uncaught JavaScript errors during all scenarios')
    (out/'results.json').write_text(json.dumps({'results':results,'errors':errors},ensure_ascii=False,indent=2),encoding='utf-8')
    browser.close()
